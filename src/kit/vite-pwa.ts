/**
 * Offline + installable (CLAUDE.md §1), at build time:
 *
 * - every HTML page gets `<link rel="manifest">` (relative to its depth) and a
 *   `theme-color` meta, so `registerPWA()` (util/pwa.ts) finds the worker
 *   from any page, under any GitHub Pages sub-path;
 * - `dist/manifest.webmanifest` (name, colours, icons: PNGs from
 *   `public/icons/icon-{192,512}.png` when present, else the SVG favicon);
 * - `dist/sw.js`: a service worker whose precache list is every page and
 *   asset in dist/ (HTML, JS, CSS, woff2, images, JSON), minus duplicates
 *   browsers never use (KaTeX/Fontsource .woff/.ttf), source maps and very
 *   large files. Pages are network-first (fresh when online, cached when
 *   not); hashed assets are cache-first. The cache name carries a content
 *   version, so a new deploy replaces the old cache on activation.
 *
 * Pure helpers (`precacheList`, `serviceWorkerSource`, `webManifest`,
 * `manifestTags`) are unit-tested in vite-pwa.test.ts.
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, posix, relative, resolve, sep } from 'node:path';
import type { Plugin } from 'vite';

export interface PwaOptions {
  name?: string;
  shortName?: string;
  description?: string;
  /** Browser UI colour (light theme paper). */
  themeColor?: string;
  backgroundColor?: string;
  /** Extra exclusions for the precache list (matched against the dist-relative path). */
  exclude?: readonly RegExp[];
  /** Files larger than this are not precached. Default 8 MB. */
  maxBytes?: number;
}

const DEFAULTS = {
  name: 'coolstuff: an interactive STEM & CS textbook',
  shortName: 'coolstuff',
  description: 'Free, interactive lessons from calculus to LLMs and physics: touch the idea, read the maths, solve the problems.',
  // SURFACES.light.paper in theme.ts (kept literal: this file runs in Node at build time).
  themeColor: '#f8f5ee',
  backgroundColor: '#f8f5ee',
};

const PRECACHE_EXT = /\.(html|js|mjs|css|woff2|svg|png|webp|jpg|jpeg|json|webmanifest|txt|wasm)$/i;
const ALWAYS_SKIP = [/(^|\/)sw\.js$/, /\.map$/, /\.(woff|ttf|eot)$/i, /(^|\/)\.[^/]+/];

/** Which dist-relative paths (posix) to precache, given their sizes. Sorted, HTML first. */
export function precacheList(files: readonly { path: string; bytes: number }[], opts: Pick<PwaOptions, 'exclude' | 'maxBytes'> = {}): string[] {
  const max = opts.maxBytes ?? 8 * 1024 * 1024;
  const skip = [...ALWAYS_SKIP, ...(opts.exclude ?? [])];
  return files
    .filter((f) => PRECACHE_EXT.test(f.path) && f.bytes <= max && !skip.some((re) => re.test(f.path)))
    .map((f) => f.path)
    .sort((a, b) => (a.endsWith('.html') === b.endsWith('.html') ? a.localeCompare(b) : a.endsWith('.html') ? -1 : 1));
}

/** A short content version for the cache name. */
export function precacheVersion(entries: readonly string[], hashes: readonly string[] = []): string {
  return createHash('sha256').update(entries.join('\n')).update(hashes.join('\n')).digest('hex').slice(0, 12);
}

/** The service worker source for a precache list (paths relative to the worker's own URL). */
export function serviceWorkerSource(precache: readonly string[], version: string): string {
  return `/* coolstuff service worker (generated by src/kit/vite-pwa.ts; do not edit) */
const CACHE = 'coolstuff-${version}';
const PRECACHE = ${JSON.stringify(precache)};
const scoped = (u) => new URL(u, self.location.href).href;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // One failed file must not break installation: settle each request on its own.
    await Promise.allSettled(PRECACHE.map((u) => cache.add(new Request(scoped(u), { cache: 'reload' }))));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('coolstuff-') && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

// Pages send the assets their first visit already loaded (util/pwa.ts).
self.addEventListener('message', (event) => {
  const data = event.data || {};
  if (data.type !== 'precache' || !Array.isArray(data.urls)) return;
  const urls = data.urls.filter((u) => typeof u === 'string' && new URL(u).origin === self.location.origin);
  const work = caches.open(CACHE).then((cache) => Promise.allSettled(urls.map((u) => cache.add(u))));
  if (event.waitUntil) event.waitUntil(work);
});

async function fromCache(request) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request, { ignoreSearch: true });
  if (hit) return hit;
  const url = new URL(request.url);
  if (url.pathname.endsWith('/')) return cache.match(url.origin + url.pathname + 'index.html');
  return undefined;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate' || request.destination === 'document') {
    // Pages: network first (fresh when online), the cached copy when offline.
    event.respondWith((async () => {
      try {
        const res = await fetch(request);
        if (res.ok) (await caches.open(CACHE)).put(request, res.clone());
        return res;
      } catch {
        return (await fromCache(request)) || new Response('<!doctype html><meta charset="utf-8"><title>Offline</title><p>You are offline and this page has not been saved yet.</p>', { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
      }
    })());
    return;
  }
  // Assets (content-hashed): cache first, then the network (and remember it).
  event.respondWith((async () => {
    const hit = await fromCache(request);
    if (hit) return hit;
    const res = await fetch(request);
    if (res.ok && res.type === 'basic') (await caches.open(CACHE)).put(request, res.clone());
    return res;
  })());
});
`;
}

/** The web app manifest object. `icons` are paths relative to the manifest. */
export function webManifest(opts: PwaOptions, icons: readonly { src: string; sizes: string; type: string; purpose?: string }[]): Record<string, unknown> {
  const o = { ...DEFAULTS, ...opts };
  return {
    name: o.name,
    short_name: o.shortName,
    description: o.description,
    start_url: './',
    scope: './',
    display: 'standalone',
    background_color: o.backgroundColor,
    theme_color: o.themeColor,
    icons,
  };
}

/** The tags a page needs, given its path relative to the site root ("lessons/a/b/index.html"); theme-color only if the page lacks one. */
export function manifestTags(pagePath: string, themeColor = DEFAULTS.themeColor, hasThemeColor = false): string {
  const depth = pagePath.split('/').length - 1;
  const up = '../'.repeat(depth);
  const link = `<link rel="manifest" href="${up}manifest.webmanifest">`;
  return hasThemeColor ? link : `${link}\n    <meta name="theme-color" content="${themeColor}">`;
}

function walk(dir: string, root: string, out: { path: string; bytes: number }[]): void {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, root, out);
    else out.push({ path: relative(root, full).split(sep).join(posix.sep), bytes: st.size });
  }
}

function iconsFor(publicDir: string): { src: string; sizes: string; type: string; purpose?: string }[] {
  const icons: { src: string; sizes: string; type: string; purpose?: string }[] = [];
  for (const size of [192, 512]) {
    if (existsSync(join(publicDir, `icons/icon-${size}.png`))) icons.push({ src: `icons/icon-${size}.png`, sizes: `${size}x${size}`, type: 'image/png', purpose: 'any maskable' });
  }
  if (existsSync(join(publicDir, 'favicon.svg'))) icons.push({ src: 'favicon.svg', sizes: 'any', type: 'image/svg+xml' });
  return icons;
}

/** The Vite plugin: manifest links in every page (build and dev), manifest + sw.js written after the bundle. */
export function pwaPlugin(opts: PwaOptions = {}): Plugin {
  let root = process.cwd();
  let outDir = 'dist';
  let publicDir = 'public';
  let isBuild = false;
  const manifestJson = () => JSON.stringify(webManifest(opts, iconsFor(publicDir)), null, 2) + '\n';
  return {
    name: 'coolstuff:pwa',
    enforce: 'post',
    configResolved(config) {
      root = config.root;
      outDir = resolve(config.root, config.build.outDir);
      publicDir = config.publicDir || join(config.root, 'public');
      isBuild = config.command === 'build';
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if ((req.url ?? '').split('?')[0].endsWith('/manifest.webmanifest')) {
          res.setHeader('Content-Type', 'application/manifest+json');
          res.end(manifestJson());
          return;
        }
        next();
      });
    },
    transformIndexHtml: {
      order: 'post',
      handler(html, ctx) {
        if (/rel=["']manifest["']/.test(html)) return html;
        const page = relative(root, ctx.filename).split(sep).join(posix.sep);
        const hasTheme = /name=["']theme-color["']/.test(html);
        return html.replace(/<\/head>/i, `    ${manifestTags(page, opts.themeColor, hasTheme)}\n  </head>`);
      },
    },
    closeBundle() {
      if (!isBuild || !existsSync(outDir)) return;
      writeFileSync(join(outDir, 'manifest.webmanifest'), manifestJson());
      const files: { path: string; bytes: number }[] = [];
      walk(outDir, outDir, files);
      const list = precacheList(files, opts);
      const hashes = list.filter((p) => p.endsWith('.html') || p === 'manifest.webmanifest').map((p) => createHash('sha1').update(readFileSync(join(outDir, p))).digest('hex'));
      writeFileSync(join(outDir, 'sw.js'), serviceWorkerSource(list, precacheVersion(list, hashes)));
    },
  };
}
