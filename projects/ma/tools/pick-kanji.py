#!/usr/bin/env python3
"""
Emit src/fonts-ja.css: @font-face rules for only the Shippori Mincho chunks
that contain the CJK characters this theme actually uses.

Why: @fontsource/shippori-mincho splits its Japanese glyphs into ~120
unicode-range chunks per weight. Importing its stock CSS makes Vite copy every
chunk (plus .woff fallbacks) into dist/: about 8 MB per weight, of which a
page needs two or three files. This script scans the content and templates
for CJK characters, finds which chunk holds each one, and declares just those.

    python3 projects/ma/tools/pick-kanji.py

Re-run it after adding posts with new kanji (e.g. a new `kanji:` field). A
character that isn't covered still renders, in the reader's system mincho.
"""
from __future__ import annotations

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.normpath(os.path.join(HERE, '..'))
REPO = os.path.normpath(os.path.join(PROJECT, '..', '..'))
FONT_DIR = os.path.join(REPO, 'node_modules', '@fontsource', 'shippori-mincho')
OUT = os.path.join(PROJECT, 'src', 'fonts-ja.css')

# Characters generated by CSS rather than typed: cjk-decimal counters (一 二 三 …).
EXTRA = '一二三四五六七八九十〇'


def is_cjk(ch: str) -> bool:
    cp = ord(ch)
    return (0x2E80 <= cp <= 0x9FFF) or (0xF900 <= cp <= 0xFAFF) or (0xFF00 <= cp <= 0xFFEF)


def used_chars() -> set[str]:
    chars = set(EXTRA)
    for dirpath, dirnames, filenames in os.walk(PROJECT):
        dirnames[:] = [d for d in dirnames if d not in ('public', 'tools', 'node_modules')]
        for name in filenames:
            if not name.endswith(('.md', '.html', '.ts', '.css', '.json')) or name == 'fonts-ja.css':
                continue
            with open(os.path.join(dirpath, name), encoding='utf8') as f:
                chars.update(c for c in f.read() if is_cjk(c))
    return chars


def parse_ranges(spec: str) -> list[tuple[int, int]]:
    out = []
    for part in spec.split(','):
        part = part.strip().removeprefix('U+')
        lo, _, hi = part.partition('-')
        out.append((int(lo, 16), int(hi or lo, 16)))
    return out


def chunks(weight: int) -> list[tuple[str, str, list[tuple[int, int]]]]:
    with open(os.path.join(FONT_DIR, f'{weight}.css'), encoding='utf8') as f:
        css = f.read()
    found = []
    for block in re.findall(r'@font-face\s*{([^}]*)}', css):
        src = re.search(r"url\(\./files/([^)]+\.woff2)\)", block)
        rng = re.search(r'unicode-range:\s*([^;]+);', block)
        if src and rng and 'latin' not in src.group(1):
            found.append((src.group(1), rng.group(1).strip(), parse_ranges(rng.group(1))))
    return found


def main() -> None:
    chars = used_chars()
    picked: dict[str, str] = {}
    missing = []
    for ch in sorted(chars):
        cp = ord(ch)
        for file, spec, ranges in chunks(400):
            if any(lo <= cp <= hi for lo, hi in ranges):
                picked[file] = spec
                break
        else:
            missing.append(ch)
    lines = [
        '/* Generated by tools/pick-kanji.py: do not edit by hand. */',
        f'/* Covers: {"".join(sorted(chars))} */',
    ]
    for file, spec in sorted(picked.items()):
        lines += [
            '@font-face {',
            "  font-family: 'Shippori Mincho';",
            '  font-style: normal;',
            '  font-display: swap;',
            # One weight serves every weight: the kanji are display accents, and a
            # range keeps 500/600 headings from falling back to a system font.
            '  font-weight: 300 800;',
            f"  src: url('../../../node_modules/@fontsource/shippori-mincho/files/{file}') format('woff2');",
            f'  unicode-range: {spec};',
            '}',
        ]
    with open(OUT, 'w', encoding='utf8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(chars)} CJK characters -> {len(picked)} font chunk(s) -> {os.path.relpath(OUT, REPO)}')
    if missing:
        print('not in Shippori Mincho (system fallback):', ''.join(missing))


if __name__ == '__main__':
    main()
